/**
 * Get voucher definition by ID
 */
export function getVoucherById(id: VoucherId): VoucherDefinition | undefined {
	return VOUCHER_REGISTRY[id];
}

/**
 * Get voucher with role-specific content
 */
export function getVoucherForRole(
	id: VoucherId,
	role: GlobalRole
): VoucherDisplay | null {
	const def = VOUCHER_REGISTRY[id];
	if (!def) return null;

	return {
		id: def.id,
		title: role === 'anh' ? def.titleAnh : def.titleEm,
		description: role === 'anh' ? def.descriptionAnh : def.descriptionEm,
		icon: def.icon,
		category: def.category,
		spicyLevel: def.spicyLevel,
		duration: def.duration,
		isRedeemed: false,
		isUsed: false,
	};
}

/**
 * Get all vouchers by category
 */
export function getVouchersByCategory(
	category: VoucherDefinition['category']
): VoucherDefinition[] {
	return Object.values(VOUCHER_REGISTRY).filter((v) => v.category === category);
}

/**
 * Get all vouchers by spicy level
 */
export function getVouchersBySpicyLevel(level: 1 | 2 | 3): VoucherDefinition[] {
	return Object.values(VOUCHER_REGISTRY).filter((v) => v.spicyLevel === level);
}



export function createVoucherReward(
	id: VoucherId,
	role: GlobalRole,
	initialState: Partial<VoucherReward> = {}
): VoucherReward | null {
	const voucherDisplay = getVoucherForRole(id, role);
	if (!voucherDisplay) return null;

	return {
		id: voucherDisplay.id,
		title: voucherDisplay.title,
		description: voucherDisplay.description,
		icon: voucherDisplay.icon,
		isRedeemed: false,
		isUsed: false,
		...initialState,
	};
}
